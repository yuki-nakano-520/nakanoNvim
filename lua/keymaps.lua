-- ==============================================
-- keymaps.lua
-- Vimのデフォルトキーバインドを活かしつつ
-- 最小限だけ追加する
-- ==============================================

local map = vim.keymap.set

-- リーダーキーをスペースキーに設定する
-- リーダーキー = 自分でショートカットを定義するときのプレフィックス
-- 例：<leader>e なら「スペース + e」で何かを実行できる
vim.g.mapleader = " "

-- ==============================================
-- 追加ショートカット（最小限）
-- ==============================================

-- ノーマルモードでCtrl+S で保存
-- :w<CR> = :wとEnterキーを押すのと同じ
map("n", "<C-s>", ":w<CR>")
