-- ==============================================
-- options.lua
-- VSCodeのsettings.jsonに相当するファイル
-- エディタの基本的な見た目や動作を設定する
-- ==============================================

-- vim.optを短くoptとして使えるようにする（毎回vim.optと書かなくて済む）
local opt = vim.opt

-- ==============================================
-- 行番号
-- ==============================================

-- 行番号を表示する（左端に1, 2, 3...と表示される）
opt.number = true

-- 相対行番号を表示する
-- カーソルがある行からの距離が表示される
-- （例：3行上なら「3」と表示される）
-- ddで3行削除したいときなど行数を数えるのに便利
opt.relativenumber = true

-- ==============================================
-- インデント（字下げ）
-- ==============================================

-- タブキーを押したときにスペースに変換する
opt.expandtab = true

-- タブ1つ分のスペース数
opt.tabstop = 2

-- 自動インデント時のスペース数
opt.shiftwidth = 2

-- 自動でいい感じにインデントしてくれる
opt.smartindent = true

-- ==============================================
-- 表示設定
-- ==============================================

-- 長い行を折り返さない
-- 折り返すと見た目がごちゃごちゃするので無効にする
opt.wrap = false

-- フルカラー表示を有効にする
-- これがないとテーマの色が正しく表示されない
opt.termguicolors = true

-- 左端のガターを常に表示する
-- ガター = git差分やエラーマークが表示される細い列
opt.signcolumn = "yes"

-- ==============================================
-- 検索設定
-- ==============================================

-- 検索時に大文字小文字を区別しない
-- 「hello」で検索すると「Hello」「HELLO」もヒットする
opt.ignorecase = true

-- 検索語に大文字が含まれる場合のみ区別する
-- 「Hello」で検索すると「hello」はヒットしない
opt.smartcase = true

-- ==============================================
-- クリップボード
-- ==============================================

-- システムのクリップボードと共有する
-- これがないとNeovimでコピーしたものを
-- ブラウザなど他のアプリに貼り付けられない
opt.clipboard = "unnamedplus"

-- ==============================================
-- パフォーマンス
-- ==============================================

-- 補完などの反応速度（ミリ秒）
-- 小さいほど速く反応する
opt.updatetime = 250

-- Neovimの背景を透明にする
-- これによりWezTermの透明度設定が透けて見えるようになる
vim.api.nvim_set_hl(0, "Normal", { bg = "none" })
vim.api.nvim_set_hl(0, "NormalFloat", { bg = "none" })
